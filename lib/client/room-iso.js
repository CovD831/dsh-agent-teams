/**
 * ── ★★★ 等距投影：把房间的地板坐标折成屏幕坐标（需求 §27.5 的画风升级）──────────────
 *
 * ── 为什么必须有这一层 ────────────────────────────────────────────────────────────
 *
 * MEASURED（2026-10-22，用户截图）：第一版房间画的是**正投影方格 + 两个灰方块**，
 * 用户评语「**目前这个很显然跟我想要的风格、跟我想的画面不一样**」。
 * 参照物（`ypyik0669/claude-web` 的 `web/src/features/cafe/`）是真房间：
 * 等距斜角、有墙有地板、有桌椅、有屏幕亮着。
 *
 * ★★ 两者的差别不是"精美程度"，是**画法**：
 * ```
 * 正投影   一格一个 div，人是一个方块      ⇒ 读起来像**表格**
 * 等距     一格是一个菱形，物体是有体积的立方体 ⇒ 读起来像**房间**
 * ```
 *
 * ── 本文件只做投影（纯数学），不画任何东西 ──────────────────────────────────────
 *
 * 与 `room-plan.ts` 的分工一致：**判断与几何在这里，绘制在 `room-canvas.ts`**。
 * 于是"某个地板坐标该落在屏幕哪里"可以被单测，而不需要浏览器。
 *
 * ★ 参数取自参照物（`iso.ts` 逐字）：`TW = 16`（格宽）、`TH = 8`（格高）——
 *   **2:1 的菱形**是像素等距的标准比例，也是"一个像素格 = 屏幕两像素"的整数倍关系。
 *
 * @module dsh-agent-teams/client/room-iso
 */
/** 一格地板的**像素宽**（菱形对角线）。 */
export const TW = 16;
/** 一格地板的**像素高**。★ `TH = TW / 2` ⇒ 菱形是 2:1，等距的标准比例。 */
export const TH = 8;
/**
 * 房间的墙有多高（像素）。
 *
 * ★★ MEASURED（2026-10-22，第三版截图）：照抄参照物的 56 但房间只有 5 排深，
 *   ⇒ 画出来是**一片墙 + 一条薄地板**。参照物的房间有 18+ 排深，56 才不会压过地板。
 * ⇒ 改成**按房间深度算**：`wallHeight(rows)`。墙与地板的比例决定"这是房间还是墙"。
 * ★ 而它必须在 24–40 之间：低于 24 看不出"墙立起来了"，高于 40 在小房间上就压掉地板。
 */
export function wallHeight(rows) {
    return Math.max(24, Math.min(40, 18 + rows * 3));
}
/**
 * 地板坐标 `(u, v)` 在高度 `h` 处的屏幕位置（相对房间的"后角"）。
 *
 * ★ 公式与参照物逐字相同：`x = (u - v) * TW/2`，`y = (u + v) * TH/2 - h`。
 *   · `u` 往**右下**走（屏幕上 x 增、y 增）
 *   · `v` 往**左下**走（屏幕上 x 减、y 增）
 *   · `h` 往**上**（屏幕 y 减）
 * ★★ 这三条合起来就是"等距"：两个地板方向在屏幕上都斜 45°，而高度是垂直的。
 */
export function toScreen(u, v, h = 0) {
    return { x: (u - v) * (TW / 2), y: (u + v) * (TH / 2) - h };
}
/**
 * 绘制顺序：离观众**远**的先画。
 * ★ 等距里"远近"就是 `u + v`：它越小越靠后（屏幕上方）。不按它排序，
 *   前面的人会被后面的人盖住 —— 而"被盖住"与"这个人不在"在画面上同形。
 */
export function depthOf(u, v) {
    return u + v;
}
/** 一个 `cols × rows` 的房间在屏幕上的包围盒（含墙高与边距）。 */
export function sceneSize(cols, rows, pad = 10) {
    return {
        width: (cols + rows) * (TW / 2) + pad * 2,
        height: (cols + rows) * (TH / 2) + wallHeight(rows) + pad * 2,
        /** ★ 后角要往右挪 `rows` 个半格 —— 否则 `u=0` 那一侧会画到画布外面去。 */
        ox: rows * (TW / 2) + pad,
        oy: wallHeight(rows) + pad,
    };
}
/** 一格地板（菱形）的四个角，按绘制顺序（顺时针）。 */
export function tileQuad(u, v) {
    return [toScreen(u, v), toScreen(u + 1, v), toScreen(u + 1, v + 1), toScreen(u, v + 1)];
}
