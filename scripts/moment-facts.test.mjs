/**
 * ── ★ 语料夹具（t51）：`docs/MOMENT-FACTS.md` 的每一条引用，是否还指向真的东西 ──────
 *
 * ── 这一臂防的是什么 ────────────────────────────────────────────────────────────
 *
 * 那份文档的主题是**「写在某个时刻的事实，在没有被复核的情况下，继续被当成本刻的事实」**。
 * ⇒ 而它自己**就是**一堆写在某个时刻的事实：台账 id、提交哈希、任务 id、文件路径。
 *
 * ★ 若没有这份夹具，那个文档会在几周后变成**它自己描述的那种东西** ——
 *   一份读起来完全正常、而其中的 id 早已不存在或改了号的归纳。
 *   **而它读起来完全正常，正是它最坏的地方。**
 *
 * ── 它检查的不是"文档写得对不对"（那不可机械判） ──────────────────────────────────
 *
 *   可机械判的是：**它的每一条引用在盘上还找不找得到。**
 *   ⇒ 一个指向不存在条目的引用，与一个指向存在条目的引用，在**人读**的时候同形
 *     （两个看起来都像一个 id），而在**机械复核**时不同形。
 *   ⇒ 这正是文档第 3 节说的"一个不指向现场的归纳，与一次猜测同形"的机械落点。
 *
 * ── 三态（本文件自己也不许把"没测到"并进"通过"）────────────────────────────────
 *
 *   · `ok`      —— 每条引用都指向盘上真实存在的东西
 *   · `blocked` —— 有一条引用指向**已不存在**的东西（文档过期了）
 *   · 并且它**必须能说清是哪一条** —— 一个只说"有问题"的检查等于没说
 *
 * ★ 为什么不断言"文档覆盖了全部长相"：那不可判，而且**文档自己第 4 节明确说了它不覆盖全部**。
 *   把它写成断言，等于要求文档自相矛盾。
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DOC = join(ROOT, 'docs/MOMENT-FACTS.md')

const source = readFileSync(DOC, 'utf8')

/** 只读地跑一条 git 命令（**全部只读**：`cat-file` / `log` / `rev-parse`，一个写命令都没有）。 */
function gitRead(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' })
}

/** 一个提交哈希在不在仓库里（拿一个不存在的版本对拍会静默给出空输出，所以要先问）。 */
function commitExists(hash) {
  try { gitRead(['cat-file', '-t', hash]); return true } catch { return false }
}

// ─────────────────────────────────────────────────────────────────────────────
// 臂 1：台账里被点名的每一条 f-XXXX 都还在
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ★ 这是本文件最重要的一臂：文档的价值建立在"**可复核**"上 ——
 *   而可复核的第一件事是**它指向的条目还在**。
 *
 * ★ 台账被整理过（`f-0024` 记过：59/78 条是夹具产物）—— 所以**条目会消失或改号**。
 *   那正是一个链接会腐烂的真实机制，而不是假设。
 */
test('臂 1 ★ 文档点名的每一个 f-XXXX 都真的存在于台账里', () => {
  const ledgerDir = join(ROOT, '.agent-teams/frictions')
  assert.ok(existsSync(ledgerDir), `★ 台账目录不存在：${ledgerDir} —— 本臂无法成立`)

  const present = new Set(
    readdirSync(ledgerDir)
      .filter((name) => /^f-\d{4}\.json$/.test(name))
      .map((name) => name.replace('.json', '')),
  )
  assert.ok(present.size > 0, '★ 台账里一条 f-XXXX 都没有 —— 本臂会在"空集"上恒真')

  /** 文档里出现的每一个 f-XXXX（去重）。 */
  const cited = [...new Set((source.match(/f-\d{4}/g) ?? []))]
  assert.ok(
    cited.length >= 5,
    `★ 文档只点名了 ${cited.length} 条台账 —— 而契约要求"每条长相指向具体条目"。`
    + '★ 少于 5 条意味着某几个长相是泛泛而谈的',
  )

  const missing = cited.filter((id) => !present.has(id))
  console.log(`    ℹ 文档点名 ${cited.length} 条台账：${cited.join(', ')}`)
  assert.deepEqual(
    missing, [],
    '★ 文档点名的台账条目**已不存在** —— 那份归纳因此指向了真空：\n'
    + missing.map((id) => `  · ${id}`).join('\n')
    + '\n★ 这正是文档自己描述的那个形态：写下的那一刻它指向真的东西，之后没有人回头问它。',
  )
})

// ─────────────────────────────────────────────────────────────────────────────
// 臂 2：文档点名的每一个提交哈希都还在仓库里
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ★ 这一臂与臂 1 同源但**不同形**：台账条目在**工作区**里，提交哈希在**历史**里。
 *   前者会被人删改，后者只在 rebase/force-push 后消失。
 *   ⇒ 两条分开检查，因为它们**失效的方式不同**（而一个把两者合成一条的实现，
 *     在一种失效时会连带掩盖另一种）。
 */
test('臂 2 ★ 文档点名的每一个提交哈希都真的在仓库历史里', () => {
  /** 形如 `5b71204` / `fe9de34` 的 7–40 位十六进制，且**以反引号或行首出现**（避免误抓普通词）。 */
  const cited = [...new Set((source.match(/`([0-9a-f]{7,40})`/g) ?? []).map((match) => match.slice(1, -1)))]
  console.log(`    ℹ 文档点名 ${cited.length} 个提交：${cited.join(', ') || '(无)'}`)

  /** ★ 空集不许通过 —— "每个元素都合法"是恒真的（文档自己引的 `5b71204` 就是这个教训）。 */
  assert.ok(
    cited.length > 0,
    '★ 文档一个提交哈希都没有点名 —— 而它声称引用了若干次实测。'
    + '★ 一个"没有引用可查"的检查是**恒真**的：它永远绿，且什么都没检查',
  )

  const missing = cited.filter((hash) => !commitExists(hash))
  assert.deepEqual(
    missing, [],
    '★ 文档点名的提交在仓库历史里**不存在** —— 那些引用已经腐烂：\n'
    + missing.map((hash) => `  · ${hash}`).join('\n')
    + '\n（若因为改历史而消失，请更新文档里那一条引用，而不是删掉这条臂。）',
  )
})

// ─────────────────────────────────────────────────────────────────────────────
// 臂 3：文档点名的每一个文件路径都还在
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ── ★ 这一臂是文档主题的**直接实例** ────────────────────────────────────────────
 *
 * 文档里列了文档**自己**引用的路径（`src/tools/*`、`docs/` 下的同级文件等）。
 * 而它记录的**第一条现场**就是"t44 的 `verify` 字段指向已改名的文件" ——
 * ⇒ 若它自己的路径烂掉了，那就是**同一个形状**发生在它身上。
 */
test('臂 3 ★ 文档引用的每一个源文件路径都还在（它记录的第一个现场就是路径腐烂）', () => {
  /**
   * 只抽**明确的路径形状**：至少两段、带已知扩展名，且不在排除表里。
   * ★ 刻意保守 —— 抽太宽会把"49 条语料"之类也当成路径，那种误报会教人忽略这条臂。
   */
  const KNOWN_EXTENSIONS = ['ts', 'js', 'mjs', 'json', 'md']
  const candidates = [...new Set(
    (source.match(/`[a-zA-Z0-9_\-./]+\.(?:ts|js|mjs|json|md)`/g) ?? [])
      .map((match) => match.slice(1, -1))
      .filter((path) => path.includes('/'))
      .filter((path) => KNOWN_EXTENSIONS.includes(path.split('.').pop()))
      /**
       * ★ 排除**通配/示意**写法：以 `*` 或 `/` 结尾的不是具体路径。
       *   而 `src/tools/*` 这种正是文档在说"搬进了那里"，它**不**是一个可检查的存在性主张。
       */
      .filter((path) => !path.includes('*'))
      .filter((path) => !path.endsWith('/')),
  )]

  console.log(`    ℹ 文档引用的具体路径 ${candidates.length} 条`)
  assert.ok(candidates.length > 0, '★ 文档一条具体路径都没引用 —— 本臂恒真')

  const missing = candidates.filter((path) => !existsSync(join(ROOT, path)))
  assert.deepEqual(
    missing, [],
    '★ 文档引用的路径**已不存在**：\n'
    + missing.map((path) => `  · ${path}`).join('\n')
    + '\n★ 而这正是文档第 ① 条现场（t44 的 verify 指向已改名的文件）同形的事 ——'
    + ' 差别只在它这次发生在文档里，不在契约里。',
  )
})

// ─────────────────────────────────────────────────────────────────────────────
// 臂 4：文档必须【自己声明会过期】（否则它就是它自己描述的那种东西）
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ── 契约原话 ──────────────────────────────────────────────────────────────────
 *
 *   「★ 不得声称它覆盖了全部 —— 要说清『这份归纳是【到某个时刻为止】的，
 *      而它本身也会过期』（★ 否则它就成了它自己描述的那种东西）」
 *
 * ★ 这一臂把那句**人话**变成一条机械可实现性：文档里必须**存在**一节说明它会过期，
 *   且那一节必须真的在说"我自己也会这样"，而不是一句免责声明。
 *
 * ★ 为什么这是可判的：一段**必须存在**的文本，与一段**可以省略**的文本不同形。
 *   省掉之后，文档仍然是通顺的 —— 那正是需要一条断言看着它的理由。
 */
test('臂 4 ★ 文档必须自己声明会过期（否则它就是它自己描述的那种东西）', () => {
  /**
   * ★ 检查的是"那一节存在且说了三件事"，不是"说了某句原文" ——
   *   绑死原文会让每一次措辞改进都撞红，而下一个人只能来放宽它。
   */
  const hasSelfExpirySection = /#{2,3}\s*4\.\s*★?\s*这份文件本身也会过期/.test(source)
  assert.ok(
    hasSelfExpirySection,
    '★ 文档没有一节声明"它自己也会过期" —— 而它描述的现象正是"写下的那一刻之后会怎样"。'
    + '★ 省掉那一节，文档读起来**完全正常** —— 这就是它需要一条断言看着的原因。',
  )

  /** 它必须说清三件事，缺一条那一节就退化成免责声明。 */
  assert.match(source, /到 2026-10-07[^。]*为止/, '★ 没有说清这份归纳是【到哪个时刻为止】的')
  assert.match(source, /不宣称它覆盖了全部|不覆盖全部/, '★ 没有声明它不覆盖全部 —— 那它就在暗示自己完备')
  assert.match(source, /什么样本会证伪\*\*它\*\*|什么样本会证伪它/, '★ 没有把那条判别动作用在它自己身上')

  /**
   * ★ 反向半边：**五个长相必须都在**，且各自带一条判别动作。
   *   缺一条 ⇒ "五个长相"这句话不成立。
   */
  const looks = ['读错位置的出口', '读了过期的来源', '契约字段过期', '样本上的巧合', '代理读数']
  const missingLooks = looks.filter((look) => !source.includes(look))
  assert.deepEqual(missingLooks, [], `★ 文档缺了这些长相：${missingLooks.join(', ')}`)
})

// ─────────────────────────────────────────────────────────────────────────────
// 臂 5：每条长相都配了判别动作（分类只是索引，动作才是价值）
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ── 这一臂是契约里那句"★★ 而每个长相都要配【判别动作】（这是文档的价值所在，不是分类）"
 *    的机械落点 ────────────────────────────────────────────────────────────────
 *
 * ── ★ 这一臂修过一次口径，值得记（它自己差点成为一个"代理读数"）───────────────
 *
 * 第一版断言：**每个长相那一节里必须出现四条动作的原文**。
 * ⇒ 它当场红了（长相二），而我去看了文档才发现：**那一节的动作用的是同义措辞**
 *   （"这条读数，来自哪里？而那个来源，凭什么还是最新的？"）——
 *   它们问的**就是**那件事，只是没有一个字与清单里的字相同。
 *
 * ★ 那说明第一版检查的是**措辞的代理**（文本匹配），不是它声称的对象
 *   （"这一节有没有把分类与动作配起来"）—— 正是本文件要防的第五个长相
 *   （代理读数：读数变化不指向它关心的事）。
 * ⇒ 改成检查**结构**：每个长相那一节里必须有一行判词是 `判别动作`
 *   —— 那是文档**自己**用来配对的结构，与措辞无关。
 *   ★ 而"四条动作都在文档里出现"仍然单独检查（它们是契约点名的四条）。
 */
test('臂 5 ★ 四条判别动作都在，且每个长相那一节都配了「判别动作」这一行', () => {
  const ACTIONS = [
    '这个读数，在什么条件下会与它声称的对象不同',
    '它来自哪里',
    '什么样本会证伪它',
    '在没有那个缺陷时还成立吗',
  ]
  const missingActions = ACTIONS.filter((action) => !source.includes(action))
  assert.deepEqual(missingActions, [], `★ 文档缺了这些判别动作：${missingActions.join(' / ')}`)

  /** 逐长相切开（`### 长相` 是分隔符）。 */
  const sections = source.split(/^### /m).slice(1)
  const lookSections = sections.filter((section) => section.startsWith('长相'))
  assert.equal(
    lookSections.length, 5,
    `★ 文档里切出 ${lookSections.length} 节"长相"（期望 5）—— 结构变了，本臂需要跟着改`,
  )

  /**
   * ★ 检查**结构**而不是措辞：每个长相那一节里必须有一个 `判别动作` 的判词行。
   *   那是文档自己用来配对的方式 ⇒ 下一个人改措辞不会撞红，而**删掉那一行**会。
   */
  const withoutAction = []
  for (const section of lookSections) {
    const title = section.split('\n')[0].trim()
    const hasActionRow = section.split('\n').some((line) => /\|\s*\*\*判别动作\*\*\s*\|/.test(line))
    if (!hasActionRow) withoutAction.push(title)
  }
  console.log(`    ℹ 逐长相检查：${lookSections.length} 节，其中 ${withoutAction.length} 节没有判别动作行`)
  assert.deepEqual(
    withoutAction, [],
    '★ 下面这些长相**只有分类、没有判别动作** —— 而契约明确说动作才是这份文档的价值：\n'
    + withoutAction.map((title) => `  · ${title}`).join('\n'),
  )

  /**
   * ★ 反向半边（缺了它，本臂在"每一节都写着一句空话"的实现上照样绿）：
   *   四条动作必须**真的分布到各节**，而不是全挤在同一节里凑数。
   */
  const sectionsWithActionText = lookSections.filter((section) =>
    ACTIONS.some((action) => section.includes(action)))
  console.log(`    ℹ 含动作原文的节数：${sectionsWithActionText.length}/${lookSections.length}`)
  assert.ok(
    sectionsWithActionText.length >= 3,
    `★ 只有 ${sectionsWithActionText.length}/5 节含动作原文 —— 动作与长相没有被真的配起来`,
  )
})

// ─────────────────────────────────────────────────────────────────────────────
// 臂 6：文档必须说清它与台账的关系（原始记录 vs 归纳）
// ─────────────────────────────────────────────────────────────────────────────

/**
 * ★ 契约要求：「说明它与台账的关系（台账是原始记录，这份是归纳）」。
 *
 * ★ 而这条关系有一个**可判**的后果，正是本文件臂 1 在做的事：
 *   归纳**必须可追溯到现场**。⇒ 文档必须说出这条纪律，否则"指向 f-XXXX"看起来只是
 *   文档的一种排版习惯，而不是它成立的条件。
 */
test('臂 6 ★ 文档说清与台账的关系，且说清"归纳必须可追溯"', () => {
  assert.match(source, /frictions/, '★ 文档没有提到台账目录 —— 那条"可复核"的链断了')
  assert.match(
    source, /原始记录/,
    '★ 文档没有说清台账是【原始记录】—— 于是它与台账的关系只是"引用了几个 id"',
  )
  assert.match(
    source, /归纳/,
    '★ 文档没有说清自己是【归纳】—— 而两者的纪律相反（记录要可重放，归纳不可重放）',
  )
  assert.match(
    source, /不指向现场的归纳，与一次猜测同形/,
    '★ 文档没有说出"不指向现场的归纳与猜测同形"—— 那是它要求每条长相都带 f-XXXX 的**理由**，'
    + '少了这句，那些 id 看起来只是排版偏好，下一个人就会省掉它们',
  )
})
