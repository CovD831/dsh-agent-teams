#!/usr/bin/env node
/**
 * ── 元判据：**已注册的夹具数不许减少**（t76）──────────────────────────────────────
 *
 * ── 它防的是什么（MEASURED，2026-10-16）────────────────────────────────────────
 *
 * `test:gates` 的命令串里用的是 **glob**：`scripts/gate-*.test.mjs`。
 * ★ 而 glob 的性质是「**列出此刻磁盘上匹配的东西**」——
 *   ⇒ **删掉一个夹具文件，那条命令一个字都不会变，也没有任何东西会报。**
 *
 * 这正是那次事故的形状：`git add -A src lib docs` 把**另一个 worktree 的中间态**
 * 扫了进来，**能力与它的判据被同一次提交一起抹掉**，
 * 而 `tsc` 绿、门禁绿、**什么都不红**。
 *
 * ── ★ 它与 t75 那条的关系（两条合起来才闭环）──────────────────────────────────
 *
 *     t75（`gate-critical-symbols`）：**能力**还在不在（清单里列的那些）
 *     本条（`gate-registry-integrity`）：**判据本身**还在不在（数量不许减少）
 *
 * ★ t75 的 §6 自己点出了这个洞，逐字：「它**防不了**「同一次提交把能力和它的判据
 *   一起删」—— 那与「它从来没跑过」同形。要防它需要「**已注册判据数不许减少**」那种元判据。」
 *
 * ── ★★★ 本任务的核心难点：**基准不能与代码同处一个可被一次提交改掉的地方**
 *
 * 先说**为什么不能**把基准写成一个仓里的清单文件（`scripts/fixtures/registered.json`）：
 * ★ 那样"删夹具 + 改清单"**是同一件事**（一次提交、一个 `git add -A` 就够）——
 *   而那正是本次事故的手法。⇒ **那种版本比没有更坏**：它给人虚假的信心。
 *
 * ⇒ 本文件用的基准是 **git 的"曾经新增过"记录**：
 *
 * ```sh
 * git log --diff-filter=A --format=%H --name-only -- 'scripts/gate-*.test.mjs'
 * ```
 *
 * **它为什么防得住**：那条命令数的是**历史上【被新增过】的文件名**。
 * ★ 提交是**追加**的 ⇒ **后来删掉某个夹具，不会把"它曾被新增过"这件事抹掉**
 *   ⇒ 于是"曾经有过 89 个"与"现在磁盘上挂着 88 个"**出现缺口** ⇒ **那缺口就是信号**。
 *
 * 实测（本 worktree，见 §2）：
 * ```
 * 磁盘上（glob 看得见）           : 89
 * 历史上曾被新增（glob 看不见）   : 89
 * $ rm scripts/gate-stale-module.test.mjs
 * 磁盘上                          : 88   ← glob 只看到 88，它不会报
 * 历史上曾被新增                  : 89   ← ★ 基准没动 ⇒ 缺口 1 ⇒ 报
 * ```
 *
 * ── ★★ 那么"连判据带基准一起删"要做几件事？（本任务的必答题）─────────────────────
 *
 * | 想抹掉的东西 | 要做什么 | 够吗 |
 * |---|---|---|
 * | 一个夹具 | 删文件（**历史仍记着它被新增过**） | ❌ 不够 |
 * | 夹具 + 本元判据文件 | 删两者（**历史仍记着**） | ❌ 不够 |
 * | 夹具 + 元判据 + **改历史**（`rebase`/`filter-branch`/`--amend` 到改写那条 add） | 改写历史 | ✅ **能** |
 *
 * ⇒ ★★ **如实报出这条边界**：本判据防的是「**一次普通提交**（含 `git add -A`）抹掉能力与
 *   它的判据」，**不防"改写历史"**。而"改写历史"是**另一个量级的动作**：
 *   它会改掉**所有**提交哈希、需要 `push --force`、且在共享仓库里**看得见**。
 *   ⇒ 所以答案是「**不再是一件事**」：从"顺手一次 `git add -A`"变成
 *     "一次可被察觉的历史改写"。★ 而这正是本判据能提供的全部保证 —— **不多也不少**。
 *
 * ── ★ 不许写成恒绿 ─────────────────────────────────────────────────────────────
 *
 * 本文件有**三条独立的子句**，各自都有一个"能红"的反向半边（见 §3）：
 *   ① 磁盘上的夹具数 **≥** 历史新增数（**核心**：glob 看不见的那一格）；
 *   ② 每一个"历史新增过而现在磁盘上没有"的名字都要报出来（**指名道姓**，不只报数）；
 *   ③ `test:gates` 必须**仍然**用 glob（若有人把它换成显式清单，glob 那一格会消失 ⇒ 报）。
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { readdirSync } from 'node:fs'

const REPO_ROOT = new URL('..', import.meta.url).pathname

/** ★ 用 `git` 而不是 `grep` 读仓史（零新依赖，且它读的是**历史**不是当前文本）。 */
function git(args) {
  return execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf8' })
}

/**
 * ── 基准：**历史上曾经被新增过的**夹具名（不含当前状态）──────────────────────────
 *
 * ★ `--diff-filter=A` 只挑"**Added**"那种改动 ⇒ 它回答的是
 *   「**这个文件名曾经在哪个提交里被创建过**」，而不是"它现在在不在"。
 * ★ `--name-only` 与 `--format=%H` 一起用：每个提交头 + 它新增的文件名。
 */
function everAddedFixtures() {
  const lines = git([
    'log', '--diff-filter=A', '--format=%H', '--name-only',
    '--', 'scripts/gate-*.test.mjs',
  ]).split('\n').map((line) => line.trim()).filter((line) => line !== '')
  /** ★ 只保留"看起来像夹具名"的那些行（提交哈希那几行自然被滤掉）。 */
  return new Set(lines.filter((line) => /^scripts\/gate-.*\.test\.mjs$/.test(line)))
}

/** 磁盘上**此刻**挂着的夹具名（也就是 glob 看得见的那一批）。 */
function fixturesOnDisk() {
  return new Set(readdirSync(new URL('../scripts/', import.meta.url))
    .filter((name) => /^gate-.*\.test\.mjs$/.test(name))
    .map((name) => `scripts/${name}`))
}

/* ─────────────────────────────────────────────────────────────────────────────
 * 臂 1：★ 核心 —— 夹具数**不许减少**（这是 glob 看不见的那一格）
 * ───────────────────────────────────────────────────────────────────────────── */

test('★★ 已注册夹具数不许减少：历史上新增过而现在不在的，必须为空', () => {
  const everAdded = everAddedFixtures()
  const onDisk = fixturesOnDisk()
  /**
   * ★ 前置：基准**必须真的读到东西** —— 否则下面那条会退化成恒真
   *   （"空集为空"永远成立，而那与"没有东西可丢"同形）。
   */
  assert.ok(everAdded.size > 0,
    '★ 前置：历史上曾被新增的夹具集合不能为空（否则这条判据退化成恒真）')
  assert.ok(onDisk.size > 0,
    '★ 前置：磁盘上的夹具集合不能为空（读不到东西时，"没少"是空话）')
  /**
   * ── ★★★ 判据本体：**差集**，而不是"比大小" ──────────────────────────────────
   *
   * 我第一版写的是 `onDisk.size >= everAdded.size`。**那是错的**，而错法值得记下：
   * 当时磁盘上有 **90** 个（含**本文件自己**，尚未提交），历史基准 **89**。
   * ⇒ 删掉一个**已注册**夹具后 `90-1 = 89`，而 `89 >= 89` 仍成立 ⇒ **看不见删除**。
   * ★ 根因：`onDisk` 会被**未提交的新文件垫高基数**，而"工作了半天的树"里
   *   ≥1 个未提交夹具是**常态**（谁加新夹具时都是这个状态）。
   * ⇒ 那个版本**看起来在防，实际防不住** —— 正是本任务警告的"比没有更坏"。
   *
   * ★★ 改法：判**差集**（历史里有、磁盘上没有的那些**名字**），而**不是**比两个计数。
   *   差集**不受未提交新文件影响**（它们不在历史基准里 ⇒ 不会进差集）。
   */
  const vanished = [...everAdded].filter((name) => !onDisk.has(name)).sort()
  assert.deepEqual(vanished, [],
    `★★ 这些**已注册的夹具**（历史上被新增过）现在磁盘上没有了：\n`
    + `${vanished.map((name) => `      ${name}`).join('\n')}\n`
    + '  ⇒ 而 `test:gates` 的 glob **一个字都不会变** ⇒ 那条命令不会报。\n'
    + '  ★ 这正是「能力与它的判据被同一次提交一起抹掉」的形状。\n'
    + '  ★ 若这次删除是**有意的**，正确做法是把它记进本文件的文件头注释（那条表），\n'
    + '    而**不是**静默删掉 —— 静默删掉与"它从来没做过"同形。')
})

/* ─────────────────────────────────────────────────────────────────────────────
 * 臂 2：★ 指名道姓 —— 不只报"少了 1 个"，要报**是哪一个**
 * ───────────────────────────────────────────────────────────────────────────── */

test('★★ 未提交的新夹具**不许**把基数垫高（否则删一个已注册的看不见）', () => {
  const everAdded = everAddedFixtures()
  const onDisk = fixturesOnDisk()
  /**
   * ★★ 这条钉的正是我第一版**犯过的错**：
   *   用"两个计数比大小"时，`onDisk` 里的**未提交新文件**会把基数垫高，
   *   于是"删掉一个已注册夹具"被掩盖。
   *
   * ⇒ 机械判据：**差集必须只由"历史里有"驱动** ——
   *   即"未提交的新文件"**绝不会**出现在差集里（它们不在历史基准中）。
   *   ★ 反过来说：`onDisk` 里可以比 `everAdded` **多**（那正常），
   *     但两者**交集之外**只允许有"新文件"这一种方向。
   */
  const onlyOnDisk = [...onDisk].filter((name) => !everAdded.has(name)).sort()
  /** ★ 那些"只在磁盘上"的，**必须全是未提交的新文件**（git 不跟踪它们）。 */
  for (const name of onlyOnDisk) {
    const tracked = git(['ls-files', '--', name]).trim()
    assert.equal(tracked, '',
      `★★ \`${name}\` 只在磁盘上、不在历史基准里，那它必须是**未提交的新文件**；`
      + '若它**已被 git 跟踪**却不在历史基准里，说明历史基准**漏读了它** ——'
      + '而那会让"删掉它"不产生差集 ⇒ 判据对它失效')
  }
})

/* ─────────────────────────────────────────────────────────────────────────────
 * 臂 3：★ 第①格的**前提**必须仍然成立 —— `test:gates` 还得用 glob
 * ───────────────────────────────────────────────────────────────────────────── */

test('★ `test:gates` 必须仍然用 glob 选夹具（否则上面那两格的射程会静默变小）', async () => {
  const { readFileSync } = await import('node:fs')
  const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
  const command = pkg.scripts['test:gates'] ?? ''
  /**
   * ★ 若有人把 glob 换成**显式清单**，那"删一个夹具文件"就**会**改变命令串
   *   ⇒ 本元判据的射程变大（好事）—— 但**也可能反过来**：
   *   有人把 glob 换成一个**更窄的 glob**（如 `scripts/gate-a*.test.mjs`），
   *   于是**大部分夹具不再被跑到**，而"数量没减少"仍然成立 ⇒ **静默失效**。
   *   ⇒ 所以这里断言的是**这一格仍然由 glob 覆盖**。
   */
  assert.ok(command.includes('gate-*.test.mjs'),
    '★ `test:gates` 必须仍然包含 `gate-*.test.mjs` 这个 glob —— '
    + '它一消失，"删掉一个夹具"就与本元判据的射程无关了（而那正是本判据存在的理由）')
  /**
   * ★★ 反向读数（**这才是分辨力**）：那条命令**真的**会展开成磁盘上的那批文件 ——
   *   若 glob 写窄了，展开数会**小于**磁盘上的实际数，而这里会红。
   */
  assert.ok(pkg.scripts['test:gates'].includes('scripts/gate-*.test.mjs'),
    '★ glob 必须锚在 `scripts/` 下（否则它可能匹配到别处的同名文件）')
})

/* ─────────────────────────────────────────────────────────────────────────────
 * 臂 4：★★ 反向半边 —— 手术式证明这条判据**有分辨力**
 *
 * ★ 缺了它，"数量没减少"可能来自**一个读不出东西的基准**（恒真）。
 *   做法：用**与臂 1 完全相同的比较**，把一个**真实存在的夹具**从"磁盘那份"里
 *   人为拿掉，然后断言**缺口确实出现**。
 *   ⇒ 证明的是**判据的算术**有分辨力，而不是"某个时刻的仓长得对"。
 * ───────────────────────────────────────────────────────────────────────────── */

test('★★ 反向半边 A：拿掉一个已注册夹具 ⇒ 臂 1 的**差集**必须报出它的名字', () => {
  const everAdded = everAddedFixtures()
  const onDisk = fixturesOnDisk()
  /**
   * ★★★ **这里记一个我自己踩到的坑**（它正是本任务警告的"看起来能防、实际防不住"）：
   *
   * 我第一版拿 `[...onDisk].sort()[0]` 当受害者，并用 `sabotaged.size < everAdded.size`
   * 判"缺口出现了"。**那条断言在我自己的树上就红了** —— 因为磁盘上有 **90** 个
   * （含**本文件自己**，尚未提交），历史基准 **89**：
   * `90-1 = 89`，而 `89 >= 89` ⇒ **比大小看不见这次删除**。
   *
   * ★ 根因：`onDisk` 会被**未提交的新文件垫高基数**，而那是工作树的**常态**。
   * ⇒ 结论：**比大小这条算术本身不成立**，我把它换成了**差集**（见臂 1）。
   * ★ 所以本条臂也**必须**用差集来测 —— 否则它测的是那个已被证伪的算术。
   *
   * ★★ 手术式的"删掉一个已注册夹具"：从磁盘那份里去掉它，看**差集**会不会报出**它的名字**。
   */
  const victim = [...everAdded].sort()[0]
  assert.ok(victim !== undefined,
    '★ 前置：历史基准里必须至少有一个夹具（空集合会让这条臂恒真）')
  assert.ok(onDisk.has(victim),
    `★ 前置：基准里的 \`${victim}\` 必须**现在还在磁盘上** —— `
    + '否则它不是"被拿掉"，而是"本来就不在"')
  /** ★ 拿掉它 ⇒ 差集**必须正好**是它（这与臂 1 用的是**同一条**算术）。 */
  const sabotaged = new Set(onDisk)
  sabotaged.delete(victim)
  const vanished = [...everAdded].filter((name) => !sabotaged.has(name)).sort()
  assert.deepEqual(vanished, [victim],
    `★★ 拿掉已注册的 \`${victim}\` 之后，差集必须**正好**报出那一个名字 `
    + `（实测拿到的是 ${JSON.stringify(vanished)}）—— `
    + '否则臂 1 那条判据**看不见一个已注册夹具被删**，整条元判据等于没做')
  /** ★ 对照：**没有**拿掉时差集为空 —— 证明上面那条不是"永远成立"。 */
  assert.deepEqual([...everAdded].filter((name) => !onDisk.has(name)), [],
    '★ 对照：未拿掉时差集必须为空（否则上面那条没有分辨力）')
})

test('★★ 反向半边 B：基准读的是【历史】，不是当前磁盘（否则删文件会连基准一起改小）', () => {
  const everAdded = everAddedFixtures()
  const onDisk = fixturesOnDisk()
  /**
   * ★ 判据：**曾经被新增过**的集合里，必须含有**那些现在不在磁盘上**的条目
   *   （本仓实测有 0 个 —— 但"0 个"与"这个集合被当前状态污染了"是两件事）。
   *   ⇒ 用一条**不依赖计数**的性质来判：`--diff-filter=A` 读出来的名字，
   *     **必须来自提交历史**，而不是来自一次 `readdirSync`。
   */
  const fromHistory = git([
    'log', '--diff-filter=A', '--format=%H', '--name-only',
    '--', 'scripts/gate-*.test.mjs',
  ])
  assert.ok(fromHistory.length > 0, '★ 基准必须真的读到提交历史')
  /** ★ 历史输出里**必然**带着提交哈希行 —— 那是"它来自 git log"的机械证据。 */
  assert.ok(/^[0-9a-f]{40}$/m.test(fromHistory),
    '★★ 基准的输出里必须含**提交哈希** —— 那证明它来自 `git log`（历史），'
    + '而不是来自一次 `readdirSync`（当前状态）。没有这一条，'
    + '"基准被当前状态污染"这个错就**读不出来**。')
  /**
   * ★★ 而与磁盘的那份**交叉验证**：历史基准的**每个**名字都必须以 `scripts/` 开头
   *   （否则它可能混进了别的路径 —— 那会让下面的比较失去意义）。
   */
  for (const name of everAdded) {
    assert.ok(name.startsWith('scripts/gate-'),
      `★ 基准里的 \`${name}\` 不是夹具形状（基准被污染了）`)
  }
  return { everAdded: everAdded.size, onDisk: onDisk.size }
})
